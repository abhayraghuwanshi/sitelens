// Renders the app's brand marks (web/src/components/BrandIcon.jsx) to plain SVG
// strings for server-rendered pages (the home page's "Plugs into what you ship
// with"), with each --brand-* colour from web/src/next/next.css filled in.
// Run after changing a mark: node scripts/build-brand-marks.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { transformWithOxc } from 'vite';
import { h, Fragment } from 'preact';

const root = new URL('../', import.meta.url);
const src = await readFile(new URL('web/src/components/BrandIcon.jsx', root), 'utf8');
const css = await readFile(new URL('web/src/next/next.css', root), 'utf8');
const colors = Object.fromEntries([...css.matchAll(/--(brand-[\w-]+):\s*(#[0-9a-fA-F]{3,8})/g)].map((m) => [m[1], m[2]]));

const { code } = await transformWithOxc(`${src}\nexport { MARKS, NAMES };`, 'BrandIcon.jsx', { jsx: { runtime: 'classic', pragma: 'h', pragmaFrag: 'Fragment' } });
globalThis.h = h; globalThis.Fragment = Fragment;
const { MARKS, NAMES } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);

const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const fill = (v) => String(v).replace(/var\(--(brand-[\w-]+)\)/g, (all, name) => colors[name] || all);
function svg(node) {
  if (node == null || node === false || node === true) return '';
  if (Array.isArray(node)) return node.map(svg).join('');
  if (typeof node !== 'object') return esc(node);
  const { children, ...props } = node.props || {};
  if (node.type === Fragment) return svg(children);
  const attrs = Object.entries(props).filter(([, v]) => v != null && v !== false)
    .map(([k, v]) => ` ${k === 'className' ? 'class' : k}="${esc(fill(v))}"`).join('');
  const inner = svg(children);
  return inner ? `<${node.type}${attrs}>${inner}</${node.type}>` : `<${node.type}${attrs}/>`;
}

const out = Object.fromEntries(Object.entries(MARKS).map(([k, v]) => [k, svg(v)]));
await writeFile(new URL('shared/brand-marks.js', root), `// Generated by scripts/build-brand-marks.mjs from web/src/components/BrandIcon.jsx. Don't edit by hand.
// Simplified stand-ins for each service's logo, used only to name the service. Each is the inside of a 24×24 SVG.
export const BRAND_MARKS = ${JSON.stringify(out, null, 2)};
export const BRAND_NAMES = ${JSON.stringify(NAMES, null, 2)};
`);
console.log(`Wrote ${Object.keys(out).length} marks to shared/brand-marks.js`);
